-- ── 6. Messages Table ──
CREATE TABLE IF NOT EXISTS public.messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender_id UUID REFERENCES public.admins(id) ON DELETE SET NULL,
  sender_name VARCHAR(255),
  receiver_id UUID REFERENCES public.admins(id) ON DELETE SET NULL,
  subject VARCHAR(255),
  text TEXT NOT NULL,
  is_broadcast BOOLEAN DEFAULT false,
  is_read BOOLEAN DEFAULT false,
  read_at TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc', now())
);

-- ── 7. Questions Table ──
CREATE TABLE IF NOT EXISTS public.questions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  question TEXT NOT NULL,
  asked_by VARCHAR(255) DEFAULT 'Anonymous',
  answer TEXT,
  answered_by UUID REFERENCES public.admins(id) ON DELETE SET NULL,
  answered_at TIMESTAMP WITH TIME ZONE,
  status VARCHAR(50) DEFAULT 'unanswered' CHECK (status IN ('unanswered', 'answered')),
  is_public BOOLEAN DEFAULT true,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc', now()),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc', now())
);

-- ── 8. Notifications Table ──
CREATE TABLE IF NOT EXISTS public.notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipient_id UUID REFERENCES public.admins(id) ON DELETE CASCADE,
  type VARCHAR(50) DEFAULT 'system' CHECK (type IN ('event', 'gallery', 'question', 'message', 'system')),
  text TEXT NOT NULL,
  link VARCHAR(255),
  is_read BOOLEAN DEFAULT false,
  read_at TIMESTAMP WITH TIME ZONE,
  meta JSONB DEFAULT '{}'::jsonb,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc', now())
);

-- ── 9. Leaders Table ──
CREATE TABLE IF NOT EXISTS public.leaders (
