-- ── 1. Admins Table ──
CREATE TABLE IF NOT EXISTS public.admins (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  email VARCHAR(255) UNIQUE NOT NULL,
  password_hash TEXT NOT NULL,
  phone VARCHAR(50),
  role VARCHAR(50) DEFAULT 'admin' CHECK (role IN ('superadmin', 'admin')),
  avatar TEXT,
  is_active BOOLEAN DEFAULT true,
  last_login TIMESTAMP WITH TIME ZONE,
  password_reset_token TEXT,
  password_reset_expires TIMESTAMP WITH TIME ZONE,
  refresh_tokens TEXT[] DEFAULT '{}',
  notification_preferences JSONB DEFAULT '{"email": true, "push": true, "approvals": true, "messages": true}'::jsonb,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc', now()),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc', now())
);

-- ── 2. Members Table ──
CREATE TABLE IF NOT EXISTS public.members (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  email VARCHAR(255) UNIQUE NOT NULL,
  phone VARCHAR(50),
  role VARCHAR(100) DEFAULT 'Member',
  status VARCHAR(50) DEFAULT 'active',
  joined TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc', now()),
  avatar TEXT,
  notes TEXT,
  created_by UUID REFERENCES public.admins(id) ON DELETE SET NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc', now()),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc', now())
);

-- Migration safety for existing tables:
DO $$
BEGIN
  -- Relax status check constraint if present
  IF EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'members_status_check') THEN
    ALTER TABLE public.members DROP CONSTRAINT members_status_check;
  END IF;
  ALTER TABLE public.members ADD CONSTRAINT members_status_check 
    CHECK (status IN ('active', 'inactive', 'pending', 'rejected', 'approved'));
EXCEPTION
  WHEN others THEN NULL;
END $$;


-- ── 3. Events Table ──
CREATE TABLE IF NOT EXISTS public.events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  date DATE,
  time TIME,
  location VARCHAR(255),
  description TEXT,
  image_url TEXT,
  category VARCHAR(100) DEFAULT 'General',
  submitted_by_name VARCHAR(255),
  submitted_by_email VARCHAR(255),
  status VARCHAR(50) DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
  submitted_by UUID,
  rejection_reason TEXT,
  approved_by UUID,
  approved_at TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc', now()),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc', now())
);

-- Migration safety for events columns
DO $$
BEGIN
  ALTER TABLE public.events ADD COLUMN IF NOT EXISTS category VARCHAR(100) DEFAULT 'General';
  ALTER TABLE public.events ADD COLUMN IF NOT EXISTS submitted_by_name VARCHAR(255);
  ALTER TABLE public.events ADD COLUMN IF NOT EXISTS submitted_by_email VARCHAR(255);
  -- Relax submitted_by FK if it exists to allow members to submit
  IF EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'events_submitted_by_fkey') THEN
    ALTER TABLE public.events DROP CONSTRAINT events_submitted_by_fkey;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'events_approved_by_fkey') THEN
    ALTER TABLE public.events DROP CONSTRAINT events_approved_by_fkey;
  END IF;
EXCEPTION
  WHEN others THEN NULL;
END $$;


-- ── 4. Gallery Table ──
CREATE TABLE IF NOT EXISTS public.gallery (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(255) DEFAULT 'Untitled',
  type VARCHAR(50) DEFAULT 'image' CHECK (type IN ('image', 'video')),
